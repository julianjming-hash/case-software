#!/usr/bin/env node
// Generate reviewable hosted Auth candidates and the Worker palette from the same design source.
// Offline only: this command has no provider client, credentials, network or send operation.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = fileURLToPath(new URL('..', import.meta.url));
export function emailColours(css) {
  const parse = source => Object.fromEntries([...source.matchAll(/--([a-z-]+):\s*(#[a-f0-9]{6})\s*;/g)].map(m => [m[1], m[2]]));
  const light = parse(css.slice(css.indexOf(':root {'), css.indexOf('@media (prefers-color-scheme: dark)')));
  const dark = parse(css.slice(css.indexOf(':root[data-theme="dark"]'), css.indexOf('}', css.indexOf(':root[data-theme="dark"]'))));
  const keys = { bg: 'ground', card: 'surface', line: 'line', ink: 'ink', muted: 'ink-muted', petrol: 'petrol', onPetrol: 'on-petrol', tint: 'petrol-tint' };
  return Object.fromEntries([['light', light], ['dark', dark]].map(([theme, values]) => [theme,
    Object.fromEntries(Object.entries(keys).map(([key, name]) => { if (!values[name]) throw Error(`missing_email_token:${theme}:${name}`); return [key, values[name]]; }))]));
}
export async function buildEmails({ check = false } = {}) {
  const colours = emailColours(await readFile(join(ROOT, 'src/client/tokens.css'), 'utf8'));
  const tokens = '// Generated by scripts/build-emails.mjs from src/client/tokens.css; do not edit.\n'
    + `export const EMAIL_COLOURS = Object.freeze({\n${Object.entries(colours).map(([theme, values]) => `  ${theme}: Object.freeze(${JSON.stringify(values)}),`).join('\n')}\n});\n`;
  async function output(path, value) {
    if (check) { if (await readFile(path, 'utf8') !== value) throw Error(`email_artifact_drift:${path}`); }
    else await writeFile(path, value);
  }
  await output(join(ROOT, 'src/shared/email-tokens.mjs'), tokens);
  const { AUTH_EMAIL_KINDS, authEmail } = await import('../src/shared/email-family.mjs');
  const folder = join(ROOT, 'docs/email-templates');
  if (!check) await mkdir(folder, { recursive: true });
  for (const kind of AUTH_EMAIL_KINDS) {
    const { html, text } = authEmail(kind);
    await output(join(folder, `${kind}.html`), html + '\n');
    await output(join(folder, `${kind}.txt`), text + '\n');
  }
  return AUTH_EMAIL_KINDS.length;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw Error('usage: build-emails.mjs [--check]');
  console.log(`email artifacts: ${await buildEmails({ check: process.argv.includes('--check') })} candidates ${process.argv.includes('--check') ? 'verified' : 'generated'} (not applied)`);
}
